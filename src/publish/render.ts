import type { RunResult } from '@agent-ci/contracts/run-result.js';

/**
 * Markdown for the static-branch pull request and the PR comment. Run output
 * is model text: mentions are neutralized (no pings), HTML comments are
 * escaped (no forged agent-ci markers), and everything is length-capped below
 * GitHub's 65,536-character body limit.
 */

const MAX_BODY = 60_000;
const MAX_SECTION = 40_000;

export const prMarker = (key: string) => `<!-- agent-ci:pr:${key} -->`;
export const commentMarker = (key: string) =>
  `<!-- agent-ci:comment:${key} -->`;

/** Make model text safe to embed: no mentions, no HTML comment markers. */
export function sanitize(text: string, max = MAX_SECTION): string {
  const cleaned = text
    .replaceAll('<!--', '&lt;!--')
    .replaceAll(/@(?=[A-Za-z0-9_-])/gu, '@\u200b');
  return cleaned.length > max
    ? `${cleaned.slice(0, max)}\n\n_(truncated)_`
    : cleaned;
}

/** Cap the body but always keep the marker (it identifies our comment). */
function cap(body: string, marker: string): string {
  const capped =
    body.length > MAX_BODY
      ? `${body.slice(0, MAX_BODY)}\n\n_(truncated)_`
      : body;
  return `${capped}\n${marker}`;
}

export interface RenderContext {
  readonly key: string;
  readonly runUrl?: string | undefined;
  readonly pullUrl?: string | undefined;
}

function reportSection(result: RunResult): string[] {
  const report = (
    result as { report?: { title?: unknown; markdown?: unknown } }
  ).report;
  if (report === undefined || typeof report.markdown !== 'string') return [];
  const title = typeof report.title === 'string' ? report.title : 'Report';
  return [`### ${sanitize(title, 200)}`, '', sanitize(report.markdown)];
}

export function renderPullBody(
  result: RunResult,
  context: RenderContext,
): string {
  const files = result.changedFiles
    .slice(0, 200)
    .map((file) => `- \`${sanitize(file, 300)}\``);
  if (result.changedFiles.length > 200) {
    files.push(`- … and ${result.changedFiles.length - 200} more`);
  }
  return cap(
    [
      `## agent-ci: ${sanitize(result.useCase, 200)}`,
      '',
      sanitize(result.summary),
      '',
      ...reportSection(result),
      '',
      '### Changed files',
      '',
      ...files,
      '',
      ...(context.runUrl === undefined ? [] : [`Run: ${context.runUrl}`, '']),
      'Generated by agent-ci. Pushes made with `GITHUB_TOKEN` do not trigger this repository’s workflows; close and reopen the pull request, or configure a GitHub App token, to run CI.',
    ].join('\n'),
    prMarker(context.key),
  );
}

export function renderComment(
  result: RunResult,
  context: RenderContext,
): string {
  const errors = result.errors
    .slice(0, 10)
    .map((error) => `- ${sanitize(error, 500)}`);
  return cap(
    [
      `### agent-ci: ${sanitize(result.useCase, 200)}`,
      '',
      `**Status:** ${result.status}${result.ok ? '' : ' (failed)'}`,
      '',
      sanitize(result.summary),
      '',
      ...(context.pullUrl === undefined
        ? []
        : [`**Pull request:** ${context.pullUrl}`, '']),
      ...(errors.length === 0 ? [] : ['**Errors:**', '', ...errors, '']),
      ...(reportSection(result).length === 0
        ? []
        : [
            '<details><summary>Report</summary>',
            '',
            ...reportSection(result),
            '',
            '</details>',
            '',
          ]),
      ...(context.runUrl === undefined ? [] : [`Run: ${context.runUrl}`]),
    ].join('\n'),
    commentMarker(context.key),
  );
}

export function renderPullTitle(result: RunResult, title?: string): string {
  const raw = title ?? `agent-ci: ${result.useCase}`;
  return raw.replaceAll(/[\r\n]+/gu, ' ').slice(0, 200);
}
